class Solution:
    def countCommas(self, n: int) -> int:
        if n<=999:
            return 0
        elif n>999 and n<= 999999:
            return n-999
        elif n>999999 and n<=999999999:
            return 2*(n-999999)+(999999-999)
        elif n>999999999 and n <= 999999999999:
            return 3*(n-999999999) + (2*(999999999-999999)) + (999999-999)
        elif n>999999999999 and n<= 999999999999999:
            return 4*(n-999999999999) + (3*(999999999999-999999999)) + (2*(999999999-999999)) + (999999-999)
        elif n>999999999999999 and n<=999999999999999999:
            return 5*(n-999999999999999) + (4*(999999999999999-999999999999))+ (3*(999999999999-999999999)) + (2*(999999999-999999)) + (999999-999)